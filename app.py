# --- 3. 核心資料邏輯 ---
def load_data():
    timestamp = int(time.time())
    url = f"https://docs.google.com/spreadsheets/d/1cZCffUUh3lczFtEq8l49fb4rkPJnEBo0CyZx8TV4OMo/export?format=csv&t={timestamp}"
    
    # 建立一個包含所有 3/31 新作業的初始表
    new_hws = ["3/31聯絡簿", "國語習作P16-17", "L4生字造詞", "L4圈詞", "國甲32-34", "成語32-33", "數習38-39"]
    init_rows = []
    for hw in new_hws:
        for s in STUDENT_LIST:
            status = "未繳交"
            if hw == "國語習作P16-17": status = "需訂正"
            # 3/31 數習特殊邏輯
            if hw == "數習38-39" and s['座號'] in ["3","4","5","6","8","9","10","11","13","15","16","17","20","21","22"]: status = "已繳交"
            init_rows.append({"座號": s['座號'], "姓名": s['姓名'], "作業名稱": hw, "繳交狀態": status, "更新日期": "2026-03-31"})
    
    all_df = pd.concat([get_base_df(), pd.DataFrame(init_rows)], ignore_index=True)
    
    try:
        r = requests.get(url, timeout=10)
        if r.status_code == 200:
            df_raw = pd.read_csv(io.StringIO(r.text))
            for i in range(len(df_raw)-1, -1, -1):
                content = str(df_raw.iloc[i, -1])
                if "座號" in content:
                    cloud_df = pd.read_csv(io.StringIO(content), dtype={'座號': str})
                    # 用雲端資料更新本地狀態
                    for _, row in cloud_df.iterrows():
                        mask = (all_df['座號'] == row['座號']) & (all_df['作業名稱'] == row['作業名稱'])
                        if any(mask):
                            all_df.loc[mask, "繳交狀態"] = row['繳交狀態']
                            all_df.loc[mask, "更新日期"] = row['更新日期']
                    break
    except:
        pass
    return all_df.drop_duplicates(subset=['座號', '作業名稱'], keep='last').reset_index(drop=True)

def save_and_sync(df):
    # 💡 關鍵優化：只同步「未繳交」和「需訂正」的項目，大幅減少字數防止 Google 拒收
    sync_df = df[df["繳交狀態"] != "已繳交"]
    st.session_state.main_df = df
    try:
        csv_str = sync_df.to_csv(index=False)
        if len(csv_str) > 30000:
            st.error("⚠️ 警告：存儲內容過大，部分舊資料可能無法同步。請考慮刪除已完成作業。")
        url = st.secrets["google_sync"]["form_url"]
        eid = st.secrets["google_sync"]["entry_id"]
        res = requests.post(url, data={eid: csv_str}, timeout=5)
        return res.status_code == 200
    except:
        return False

